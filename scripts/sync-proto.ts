import { readFileSync, writeFileSync } from "node:fs"

import { $ } from "bun"

/**
 * Writes the protobuf code for the phone ↔ watch sync from proto/sync.proto, for both apps.
 * Run with `bun run proto:sync` after changing the schema, and commit what it writes.
 */

const PROTO = "proto/sync.proto"
const PHONE = "apps/mobile/src/features/watch/sync-proto"
const WATCH = "apps/watch/entry/src/main/ets/features/link/SyncProto"

const NOTE = `// Generated by scripts/sync-proto.ts from ${PROTO}. Do not edit.\n`
// 64-bit fields are timestamps in ms, well inside a double. Without this, protobuf.js returns a
// Long object where the `long` package is found and a number where it is not.
const NUMBERS = "$protobuf.util.Long = undefined\n$protobuf.configure()\n"

// No create, verify or JSON conversion: the apps encode plain objects and check what they decode.
await $`pbjs -t static-module -w es6 --force-number --no-create --no-verify --no-convert --no-delimited -o ${PHONE}.js ${PROTO}`
await $`pbts -o ${PHONE}.d.ts ${PHONE}.js`

function rewrite(path: string, from: string, to: string) {
  const text = readFileSync(path, "utf8")
  if (!text.includes(from)) throw new Error(`${path}: no ${from}`)
  writeFileSync(path, NOTE + text.replace(from, to))
}

// With --force-number nothing uses Long, and ArkTS does not take `import = require`.
const unusedLong = 'import Long = require("long");\n'
const declarations = readFileSync(`${PHONE}.d.ts`, "utf8")
if (!declarations.includes(unusedLong) || declarations.split("Long").length !== 2) {
  throw new Error(`${PHONE}.d.ts: expected one unused Long import`)
}
writeFileSync(`${PHONE}.d.ts`, declarations.replace(unusedLong, ""))

const js = readFileSync(`${PHONE}.js`, "utf8")
const dts = readFileSync(`${PHONE}.d.ts`, "utf8")
// pbts drops some interfaces without a word, as it did for messages declared after an enum.
for (const [, name] of js.matchAll(/@interface (\w+)/g)) {
  if (!dts.includes(`export interface ${name} `)) throw new Error(`pbts left out ${name}`)
}
const minimal = 'import * as $protobuf from "protobufjs/minimal";\n'
const full = 'import * as $protobuf from "protobufjs";\n'

rewrite(`${PHONE}.js`, minimal, minimal + NUMBERS)
rewrite(`${PHONE}.d.ts`, full, full)

// The HarmonyOS port of protobuf.js, imported as its README says. The ArkTS compiler reads the
// types of a JavaScript file from a .d.ets next to it, not from a .d.ts.
writeFileSync(`${WATCH}.js`, js)
writeFileSync(`${WATCH}.d.ets`, dts)
const ohos = "import $protobuf from '@ohos/protobufjs';\n"
rewrite(`${WATCH}.js`, minimal, ohos + NUMBERS)
rewrite(`${WATCH}.d.ets`, full, ohos)
