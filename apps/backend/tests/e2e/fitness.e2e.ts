import { test, expect } from '@playwright/test';

test('fitness data survives independent HTTP requests with user isolation', async ({ request }) => {
  const signup = await request.post('/auth/sign-up', { data: { email: `fitness_${crypto.randomUUID()}@fitwear.dev`, password: 'FitnessPassword123!', birthDate: '1994-04-12' } });
  expect(signup.status()).toBe(200);
  const account = await signup.json();
  const headers = { Authorization: `Bearer ${account.session.token}` };
  const date = '2026-10-29';
  expect((await request.put('/health/weight', { headers, data: { weightKg: 73.2, date } })).status()).toBe(200);
  const weights = await request.get(`/health/weights?from=${date}&to=${date}`, { headers });
  expect((await weights.json()).weights).toEqual(expect.arrayContaining([expect.objectContaining({ loggedDate: date, weightKg: 73.2 })]));
  expect((await request.put('/targets', { headers, data: { date, calorieTargetKcal: 2100, proteinTargetG: 140, carbsTargetG: 250, fatTargetG: 60 } })).status()).toBe(200);
  const mealResponse = await request.post('/meals', { headers, data: { targetDate: date, mealType: 'lunch', items: [{ foodName: 'Rice', estimatedWeightG: 200, caloriesKcal: 260, proteinG: 5, carbsG: 57, fatG: 1 }] } });
  expect(mealResponse.status()).toBe(200);
  const meal = await mealResponse.json();
  const summary = await request.get(`/meals/summary?date=${date}`, { headers });
  expect(await summary.json()).toMatchObject({ consumed: { caloriesKcal: 260 }, remaining: { caloriesKcal: 1840 } });

  const recovery = { area: 'Right shoulder', restDays: 2, lightDays: 3, startDate: date, note: 'Rest after strain' };
  expect((await request.put('/health/recovery', { headers, data: recovery })).status()).toBe(200);
  expect(await (await request.get('/health/recovery', { headers })).json()).toMatchObject({ recovery });
  const catalog = await (await request.get('/exercises?q=Bench', { headers })).json();
  const exercise = catalog.exercises[0];
  expect(exercise).toBeDefined();
  const created = await request.post('/workouts', { headers, data: { sessionTitle: 'Chest', workoutSplit: 'chest', startedAt: `${date}T10:00:00.000Z` } });
  expect(created.status()).toBe(200);
  const session = await created.json();
  expect((await request.post(`/workouts/${session.id}/sets`, { headers, data: { exerciseId: exercise.id, weightKg: 40, userConfirmedReps: 10 } })).status()).toBe(200);
  expect((await request.post(`/workouts/${session.id}/complete`, { headers, data: { completedAt: `${date}T10:30:00.000Z` } })).status()).toBe(200);
  const persisted = await (await request.get(`/workouts/${session.id}`, { headers })).json();
  expect(persisted.sets).toEqual(expect.arrayContaining([expect.objectContaining({ weightKg: 40, userConfirmedReps: 10 })]));
  const stats = await (await request.get(`/workouts/stats?from=${date}&to=${date}`, { headers })).json();
  expect(stats.totalVolumeKg).toBe(400);
  expect(stats.sessionCount).toBe(1);
  const stranger = await (await request.post('/auth/sign-up', { data: { email: `other_${crypto.randomUUID()}@fitwear.dev`, password: 'FitnessPassword123!' } })).json();
  const otherHeaders = { Authorization: `Bearer ${stranger.session.token}` };
  expect((await request.get(`/meals/${meal.id}`, { headers: otherHeaders })).status()).toBe(404);
  expect((await request.get(`/workouts/${session.id}`, { headers: otherHeaders })).status()).toBe(404);
  expect((await request.delete(`/meals/${meal.id}`, { headers })).status()).toBe(200);
  expect((await request.delete(`/workouts/${session.id}`, { headers })).status()).toBe(200);
  expect((await request.delete('/health/recovery', { headers })).status()).toBe(200);
  expect((await request.post('/auth/sign-out', { headers })).status()).toBe(200);
  expect((await request.get('/meals', { headers })).status()).toBe(401);
});
